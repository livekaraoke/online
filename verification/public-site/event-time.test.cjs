const assert = require('node:assert/strict');
const t = require('../../js/public-event-time');
const iso = (date) => date?.toISOString() ?? null;
assert.equal(iso(t.start({date:'2026-01-14',startTime:'20:00'})), '2026-01-14T19:00:00.000Z');
assert.equal(iso(t.start({date:'2026-07-15',startTime:'20:00'})), '2026-07-15T18:00:00.000Z');
assert.equal(iso(t.start({date:'2026-03-29',startTime:'01:30'})), '2026-03-29T00:30:00.000Z');
assert.equal(iso(t.start({date:'2026-03-29',startTime:'03:30'})), '2026-03-29T01:30:00.000Z');
assert.equal(t.localInstant('2026-03-29','02:30'), null);
assert.equal(iso(t.localInstant('2026-10-25','02:30')), '2026-10-25T00:30:00.000Z');
assert.equal(iso(t.end({date:'2026-10-24',startTime:'23:00',endTime:'03:00'})), '2026-10-25T02:00:00.000Z');
assert.equal(t.start({date:'2026-02-30',startTime:'20:00'}),null);
assert.equal(t.start({date:'2026-10-07',startTime:'25:00'}),null);
assert.equal(t.end({date:'2026-10-07',startTime:'20:00'}),null);
const instant = new Date('2026-12-01T22:00:00Z');
assert.equal(iso(t.start({startAt:{toDate:()=>instant},date:'2026-01-01'})),iso(instant));
assert.equal(iso(t.start({startTimestamp:{seconds:instant.getTime()/1000,nanoseconds:0}})),iso(instant));
assert.equal(t.time(instant),'23:00');
assert.equal(t.localDate(new Date('2026-07-15T23:00:00Z')),'2026-07-16');
assert.equal(t.instant('2026-01-14T20:00:00'),null);
const list = [{id:2,startAt:instant},{id:1,date:'2026-01-14',startTime:'20:00'}].sort(t.compare);
assert.deepEqual(list.map(x=>x.id),[1,2]);
console.log('Malta event-time checks passed; visitor zone:',process.env.TZ || 'default');
